/*
 * Campaign landing-page beacon.
 *
 * Included from index.html. Does nothing at all unless the visitor arrived
 * from a campaign link, so it is inert for ordinary traffic.
 *
 * What it is for
 * --------------
 * Corporate security products — Microsoft Defender Safe Links, Proofpoint,
 * Mimecast, Barracuda — fetch every link in an email before the recipient
 * ever sees it. At the redirect those fetches are indistinguishable from a
 * real click, because a scanner can forward the recipient's own browser
 * string.
 *
 * What they do not do is run JavaScript. So a request that only ever happens
 * because a script executed is evidence a person actually opened the page.
 * That is the entire basis for the difference between a click the dashboard
 * reports as inferred and one it reports as verified.
 *
 * Deliberately a plain image request rather than fetch or sendBeacon: no
 * preflight, no CORS configuration to keep in step across two origins, and no
 * dependency on anything else the page loads.
 *
 * It sends no personal data. The token identifies one sent message and was
 * generated by us; the recipient's address never appears in it.
 */
(function () {
  "use strict";

  var PARAM = "ab_t";

  /* Where to report to.
   *
   * Normally derived from the referrer, which is the tracking host itself:
   * the visitor got here through its redirect a moment ago, and the default
   * referrer policy sends the origin on a cross-origin navigation. Deriving
   * it means the tracking domain is configured in exactly one place — the
   * app's own settings — instead of being duplicated into this file where it
   * would silently go stale the day someone changes it.
   *
   * The data attribute is the override for when a referrer policy strips it.
   */
  function trackingBase() {
    var tag =
      document.currentScript ||
      document.querySelector("script[data-tracking-base]");
    var explicit = tag && tag.getAttribute("data-tracking-base");
    if (explicit) return explicit.replace(/\/+$/, "");

    if (!document.referrer) return null;
    try {
      var url = new URL(document.referrer);
      // https only: the token should not be put on the wire in clear, and a
      // referrer that is not https is not our redirect.
      if (url.protocol !== "https:") return null;
      // Never report back to ourselves — that would mean the visitor came
      // from another page on this site, not from a campaign redirect.
      if (url.host === window.location.host) return null;
      return url.origin;
    } catch (e) {
      return null;
    }
  }

  try {
    var params = new URLSearchParams(window.location.search);
    var token = params.get(PARAM);
    if (!token) return;

    // Anything other than a token we minted is not ours and is not worth
    // sending anywhere.
    if (!/^[A-Za-z0-9_-]{16,64}$/.test(token)) return;

    var base = trackingBase();
    if (base) {
      // Fire and forget. No callback and no retry: a lost beacon costs one
      // upgrade from inferred to verified on one click, which is not worth
      // any complexity here.
      var img = new Image(1, 1);
      img.decoding = "async";
      img.src = base + "/t/b/" + encodeURIComponent(token) + "?r=" + Date.now();
    }

    // Take the token back out of the address bar whether or not the beacon
    // fired. It identifies one sent message, so leaving it there means it
    // travels into anything the visitor copies, shares or bookmarks, and into
    // any analytics tool on the page that records full URLs.
    if (window.history && window.history.replaceState) {
      params.delete(PARAM);
      var query = params.toString();
      window.history.replaceState(
        null,
        "",
        window.location.pathname + (query ? "?" + query : "") + window.location.hash
      );
    }
  } catch (e) {
    // Never let tracking break the page it is measuring.
  }
})();
